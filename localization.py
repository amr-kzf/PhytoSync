def translate_text(value: str, language: str) -> str:
    if language != "ar":
        return value

    translated = AR_TRANSLATIONS.get(value)
    if translated is not None:
        return translated

    translated = next(
        (translation for source, translation in AR_TRANSLATIONS.items() if source.lower() == value.lower()),
        None,
    )
    if translated is not None:
        return translated

