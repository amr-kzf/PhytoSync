def localize_disease_result(result: dict, language: str) -> dict:
    localized = dict(result)
    if language != "ar":
        return localized

    if "label" in localized:
        localized["display_label"] = translate_text(localized["label"], language)
    if "precautions" in localized:
        localized["display_precautions"] = [
            translate_text(item, language) for item in localized["precautions"]
        ]
    if "quality_warnings" in localized:
        localized["display_quality_warnings"] = [
            translate_text(item, language) for item in localized["quality_warnings"]
        ]
    if "model_notice" in localized:
        localized["display_model_notice"] = translate_text(localized["model_notice"], language)
    if localized.get("crop_filter_applied"):
        localized["display_crop_filter_applied"] = translate_text(
            localized["crop_filter_applied"].capitalize(), language
        )
    if "alternatives" in localized:
        localized["alternatives"] = [
            {**item, "display_label": translate_text(item["label"], language)}
            for item in localized["alternatives"]
        ]
    if "crop_refinements" in localized:
        localized["crop_refinements"] = [
            {
                **item,
                "display_name_ar": translate_text(item.get("display_name", ""), language),
                "disease_name_ar": translate_text(item.get("disease_name", ""), language),
            }
            for item in localized["crop_refinements"]
        ]
    return localized
